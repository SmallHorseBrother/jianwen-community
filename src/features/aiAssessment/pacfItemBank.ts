export function getPACFItemsByIds(ids: string[]): PACFItem[] {
  const byId = new Map(pacfCandidateItemBank.map((item) => [item.id, item]));
  return ids.map((id) => {
    const item = byId.get(id);
    if (!item) throw new Error(`PACF item not found: ${id}`);
    return item;
  });
}
