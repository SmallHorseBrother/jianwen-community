export type PACFDimension = 'M' | 'F' | 'T' | 'V' | 'C' | 'S';
export type PACFItemType = 'objective' | 'scenario' | 'constructed' | 'practical';
export type PACFTargetLevel = 1 | 2 | 3 | 4 | 5;

export type PACFOption = {
  id: 'A' | 'B' | 'C' | 'D';
  text: string;
  score: 0 | 1 | 2 | 3;
};

export type PACFRubricCriterion = {
  id: string;
  description: string;
  maxPoints: 1;
};

export type PACFItem = {
  id: string;
  competencyId: string;
  dimension: PACFDimension;
  targetLevel: PACFTargetLevel;
  type: PACFItemType;
  stem: string;
  options?: PACFOption[];
  rubric?: PACFRubricCriterion[];
  rationale: string;
  sourceAnchors: string[];
  quickEligible: boolean;
  status: 'candidate';
};

const optionIds = ['A', 'B', 'C', 'D'] as const;

function rotateOptions<T>(competencyId: string, values: T[]): T[] {
  const rotation = (Number(competencyId.slice(1)) - 1) % values.length;
  return [...values.slice(rotation), ...values.slice(0, rotation)];
}

function objective(
  competencyId: string,
  dimension: PACFDimension,
  targetLevel: PACFTargetLevel,
  stem: string,
  choices: [string, string, string, string],
  correctIndex: 0 | 1 | 2 | 3,
  rationale: string,
  sourceAnchors: string[],
): PACFItem {
  const scoredChoices = choices.map((text, index) => ({ text, score: index === correctIndex ? 3 as const : 0 as const }));
  return {
    id: `PACF-${competencyId}-O1`, competencyId, dimension, targetLevel, type: 'objective', stem,
    options: rotateOptions(competencyId, scoredChoices).map((choice, index) => ({ id: optionIds[index], ...choice })),
    rationale, sourceAnchors, quickEligible: true, status: 'candidate',
  };
}

function scenario(
  competencyId: string,
  dimension: PACFDimension,
  targetLevel: PACFTargetLevel,
  stem: string,
  choicesFromWeakToStrong: [string, string, string, string],
  rationale: string,
  sourceAnchors: string[],
): PACFItem {
  const scoredChoices = choicesFromWeakToStrong.map((text, index) => ({ text, score: index as 0 | 1 | 2 | 3 }));
  return {
    id: `PACF-${competencyId}-S1`, competencyId, dimension, targetLevel, type: 'scenario', stem,
    options: rotateOptions(competencyId, scoredChoices).map((choice, index) => ({ id: optionIds[index], ...choice })),
    rationale, sourceAnchors, quickEligible: true, status: 'candidate',
  };
}

function responseItem(
  competencyId: string,
  dimension: PACFDimension,
  targetLevel: PACFTargetLevel,
  type: 'constructed' | 'practical',
  stem: string,
  criteria: [string, string, string, string],
  rationale: string,
  sourceAnchors: string[],
): PACFItem {
  return {
    id: `PACF-${competencyId}-${type === 'constructed' ? 'C1' : 'P1'}`,
    competencyId, dimension, targetLevel, type, stem,
    rubric: criteria.map((description, index) => ({ id: `${competencyId}-${index + 1}`, description, maxPoints: 1 })),
    rationale, sourceAnchors, quickEligible: false, status: 'candidate',
  };
}

